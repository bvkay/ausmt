"""EMTF XML is a FIRST-CLASS submission input alongside EDI and MTH5 (owner ruling 2026-08-03), so a
station whose transfer function arrives only as EMTF XML must build and serve the FULL product set,
and a station that has both must resolve to its EDI.

Every test here runs the REAL build (build_portal.main over a package on disk) rather than asserting
on hand-built structures, and every EMTF XML fixture is generated by the engine's own emitter from
the vendored sample survey, so the ingest path is exercised against bytes this build actually writes.

Pre-fix (revert engine/extract/build_portal.py): transfer_functions/emtfxml/ is not enumerated at
all, so an XML-only package builds 0 stations and the build FAILS with rc 2 ("pipeline produced 0
stations") -- every test below goes red on that.
"""
