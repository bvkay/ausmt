def test_declared_frame_is_read_from_the_file_not_from_a_library_default(tmp_path):
    """C25 honesty on the XML path. The frame an EMTF XML declares lives in
    <Site><Orientation angle_to_geographic_north=...>. mt_metadata 1.0.9's EMTF-XML reader leaves the
    TF's own _rotation_angle at a bare 0 regardless of what the file says, so reading THAT would
    report every station as 'declared-zero' -- a library default asserted as a station fact.

    FAILS IF a station whose file declares 30 degrees is recorded as declared-zero (the pre-fix
    behaviour of reading _rotation_angle), or if the station is refused rather than served as stored.
    The sibling, which really does declare 0, must still read declared-zero."""
    pkg = _package(tmp_path / "surveys", xml_stations=("EXAMPLE01", "EXAMPLE02"))
    victim = pkg / "transfer_functions" / "emtfxml" / "EXAMPLE01.xml"
    text = victim.read_text(encoding="utf-8")
    assert 'angle_to_geographic_north="0.000"' in text, \
        "fixture assumption: the emitter writes the site Orientation angle"
    victim.write_text(text.replace('angle_to_geographic_north="0.000"',
                                   'angle_to_geographic_north="30.000"'), encoding="utf-8")

    rc, out, prod = _build(tmp_path, tmp_path / "surveys")
    assert rc == 0
    a = json.loads((prod / SLUG / "EXAMPLE01" / "station.json").read_text(encoding="utf-8"))["frame"]
    b = json.loads((prod / SLUG / "EXAMPLE02" / "station.json").read_text(encoding="utf-8"))["frame"]
    assert a["frame_served"] == "declared-azimuth" and a["declared_azimuth_deg"] == 30.0, a
    assert a["evidence"]["orientation_angle_to_geographic_north_deg"] == 30.0, a["evidence"]
    assert a["derotated"] is False, "v3 never rotates: the frame is recorded, not corrected"
    assert b["frame_served"] == "declared-zero" and b["declared_azimuth_deg"] == 0.0, b


def test_per_period_rotation_declaration_refuses_the_station():
    """C25 POLICY v3 applies to the XML path too: AusMT serves data AS STORED and never serves a
    per-period-mixed frame, so the XML frame reader must REFUSE a per-period declaration rather than
    pick one of the angles.

    Exercised at the unit seam on purpose: on the pinned mt_metadata no real EMTF XML reaches this
    branch (the reader collapses the file's frame to a single site-level Orientation), so there is no
    fixture that can drive it. This is the non-vacuity proof that the fail-closed guard CAN fail --
    it stops the XML path from silently serving what the EDI path refuses, should a future reader
    surface per-period angles.

    FAILS IF a per-period rotation is served, or is served under one of its own angles."""
    class _Ori:
        angle_to_geographic_north = 0.0
        reference_frame = "geographic"

    class _SM:
        orientation = _Ori()

    class _TF:
        station_metadata = _SM()
        _rotation_angle = [0.0, 0.0, 30.0, 30.0]

    facts, fail = bp._emtfxml_frame(_TF(), 4)
    assert fail and "per-period" in fail.lower(), fail
    assert "30" in fail and "never serves a per-period-mixed frame" in fail, fail
    assert "frame_served" not in facts, "a refused station is never given a served-frame verdict"

    # control: the same station with ONE declared angle serves as stored
    _TF._rotation_angle = [30.0, 30.0, 30.0, 30.0]
    _Ori.angle_to_geographic_north = 30.0
    facts, fail = bp._emtfxml_frame(_TF(), 4)
    assert fail is None and facts["frame_served"] == "declared-azimuth", (facts, fail)
    assert facts["declared_azimuth_deg"] == 30.0, facts

    # and an EMTF XML that asserts NO orientation is recorded as not-asserted, never as zero
    _Ori.angle_to_geographic_north = None
    facts, fail = bp._emtfxml_frame(_TF(), 4)
    assert fail is None and facts["frame_served"] == "not-asserted", facts
    assert facts["declared_azimuth_deg"] is None, facts


def test_a_generated_edi_and_its_survey_zip_are_byte_reproducible_across_builds(tmp_path):
    """THE SERVED-EDI CROSS-BUILD INVARIANT, over the source format that could break it. The
    manifest reference states that the served EDI and the per-survey EDI zip are byte-reproducible
    across builds, so their SHA-256 is a stable cross-build invariant, unlike the EMTF XML and the
    MTH5. That was free while every served EDI was a custodian copy. An EMTF-XML-sourced station's
    EDI is WRITTEN by mt_metadata, whose EDI header writer stamps FILEDATE with the wall clock at
    write time, so without the source-stamped FILEDATE the generated file (and the survey zip that
    carries it) hashes differently on every build.

    ONE package, built TWICE, with the input bytes checked unchanged in between so a drifting digest
    can only come from the build. test_manifest.py's determinism test cannot see this: the sample
    survey it builds is EDI-only, so no generated EDI exists in it.

    FAILS IF a served EDI or the EDI zip changes digest across two builds of one package, or if the
    generated EDI's FILEDATE is not its source document's own creation time."""
    surveys = tmp_path / "surveys"
    pkg = _package(surveys, xml_stations=("EXAMPLE02",), edi_stations=("EXAMPLE01",))
    before = {p.relative_to(pkg).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in sorted(pkg.rglob("*")) if p.is_file()}

    rc1, out1, _p1 = _build(tmp_path / "b1", surveys)
    rc2, out2, _p2 = _build(tmp_path / "b2", surveys)
    assert rc1 == 0 and rc2 == 0, (rc1, rc2)
    after = {p.relative_to(pkg).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
             for p in sorted(pkg.rglob("*")) if p.is_file()}
    assert before == after, "the build must not modify the submitted package it is reading"

    m1, m2 = _docs(out1)["manifest"], _docs(out2)["manifest"]
    assert _docs(out1)["build_report"]["surveys"][SLUG]["ingest_sources"] == \
        {"EXAMPLE01": "edi", "EXAMPLE02": "emtfxml"}, "fixture sanity: one station per source format"

    def digests(man, fmt, scope):
        return sorted((r["url"], r["sha256"]) for r in man[scope] if r["format"] == fmt)

    edi1 = digests(m1, "edi", "files")
    assert len(edi1) == 2, f"both stations must serve an EDI: {edi1}"
    assert edi1 == digests(m2, "edi", "files"), \
        f"served EDI digests drifted across two builds of ONE package: {edi1} vs {digests(m2, 'edi', 'files')}"
    zip1 = digests(m1, "edi-zip", "bundles")
    assert zip1 and zip1 == digests(m2, "edi-zip", "bundles"), \
        f"the survey EDI zip digest drifted across two builds: {zip1} vs {digests(m2, 'edi-zip', 'bundles')}"

    # the mechanism, not just the symptom: the generated file carries its SOURCE document's date
    gen_url = next(r["url"] for r in m1["files"] if r["format"] == "edi" and r["station"] == "EXAMPLE02")
    text = (out1 / gen_url).read_text(encoding="utf-8", errors="replace")
    filedate = re.search(r"^\s*FILEDATE=(.+?)\s*$", text, re.M)
    source_date = re.search(r"^\s*original_file\.date=(.+?)\s*$", text, re.M)
    assert filedate and source_date, "the generated EDI must carry both a FILEDATE and a source date"
    assert filedate.group(1) == source_date.group(1), \
        f"FILEDATE must be the source document's own date, got {filedate.group(1)} vs {source_date.group(1)}"
